// verify pins -> generate src/original.generated.js (pinned original wrapped in a function giving it `marinara`; only the build-time
// phrase table src/text-map.json is applied to the generated copy, each entry asserted; vendor/ is never touched) -> bun build.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { verify } from './verify-original.mjs';
const root = new URL('../', import.meta.url).pathname;
const bad = verify(root);
if (bad.length) { console.error('original differs from pin:\n' + bad.join('\n')); process.exit(1); }
let js = readFileSync(root + 'vendor/original/extension.js', 'utf8');
const css = readFileSync(root + 'vendor/original/extension.css', 'utf8') + '\n/* adapter overrides */\n' + readFileSync(root + 'src/overrides.css', 'utf8');
const table = JSON.parse(readFileSync(root + 'src/text-map.json', 'utf8'));
const applied = [];
for (const { from, to, count } of table) {
    const n = js.split(from).length - 1;
    if (n !== count) { console.error(`text-map: expected ${count} x ${JSON.stringify(from)}, found ${n}`); process.exit(1); }
    js = js.split(from).join(to); applied.push(n);
}
writeFileSync(root + 'src/original.generated.js', `// GENERATED by scripts/build.mjs. The pinned original, with only the text-map.json phrases replaced.\nexport const ORIGINAL_CSS = ${JSON.stringify(css)};\nexport function runOriginal(marinara) {\n${js}\n}\n`);
mkdirSync(root + 'dist', { recursive: true });
for (const [e, target] of [['backend', 'bun'], ['frontend', 'browser']]) {
    const p = spawnSync(process.env.BUN_BIN || 'bun', ['build', `src/${e}.ts`, '--outfile', `dist/${e}.js`, '--target', target, '--format', 'esm'], { cwd: root, stdio: 'inherit' });
    if (p.status !== 0) throw new Error('bun build failed: ' + e);
}
console.log(JSON.stringify({ ok: true, textMap: applied }));
