// verify pins -> generate src/original.generated.js (original wrapped in a function giving it `marinara`; nothing patched) -> bun build.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { verify } from './verify-original.mjs';
const root = new URL("../", import.meta.url).pathname, here = new URL('../', import.meta.url).pathname;
const bad = verify(root);
if (bad.length) { console.error('original differs from pin:\n' + bad.join('\n')); process.exit(1); }
const js = readFileSync(root + 'vendor/original/extension.js', 'utf8'), css = readFileSync(root + 'vendor/original/extension.css', 'utf8');
writeFileSync(here + 'src/original.generated.js', `// GENERATED by scripts/build.mjs. The original is embedded byte-for-byte.\nexport const ORIGINAL_CSS = ${JSON.stringify(css)};\nexport function runOriginal(marinara) {\n${js}\n}\n`);
mkdirSync(here + 'dist', { recursive: true });
for (const [e, target] of [['backend', 'bun'], ['frontend', 'browser']]) {
    const p = spawnSync(process.env.BUN_BIN || 'bun', ['build', `src/${e}.ts`, '--outfile', `dist/${e}.js`, '--target', target, '--format', 'esm'], { cwd: here, stdio: 'inherit' });
    if (p.status !== 0) throw new Error('bun build failed: ' + e);
}
console.log(JSON.stringify({ ok: true }));
