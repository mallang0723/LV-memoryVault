const root = new URL('../', import.meta.url).pathname;
const read = f => readFileSync(root + f, 'utf8');
// ALL_PERMISSIONS of lumiverse-spindle-types 0.6.49 (what Lumiverse origin/main pins, 2026-10-24) - the oldest host we support.
const MAIN_PERMISSIONS = ['screen_capture', 'screen_recording', 'system_audio', 'generation', 'interceptor', 'tools', 'cors_proxy', 'context_handler', 'ephemeral_storage', 'chat_mutation', 'event_tracking', 'ui_panels', 'app_manipulation', 'oauth', 'characters', 'chats', 'presets', 'world_books', 'regex_scripts', 'regex_scripts_unrestricted', 'databanks', 'memories', 'media', 'personas', 'push_notification', 'decisions', 'image_gen', 'images', 'generation_parameters', 'macro_interceptor', 'web_search', 'unsafe_eval', 'final_response', 'providers.embedding.register', 'providers.tts.register', 'providers.stt.register', 'providers.sidecar.register', 'mcp_servers', 'mcp_servers.create'];

test('pins: the original is byte-identical to the author\'s v2.1.1 files', () => {
    assert.deepEqual(verify(root), []);
    assert.equal(createHash('sha256').update(readFileSync(root + 'vendor/original/extension.js')).digest('hex'), 'a183f7243c801f10b9841ec5ebecb62ecdfe21119f20f29dab6cfcb7f410c089');
    assert.equal(createHash('sha256').update(readFileSync(root + 'vendor/original/extension.css')).digest('hex'), '34de20009edf869f7af1d85ba88045118426d091b7dc5458d4cec19add1fa9f7');
    assert.equal(Object.keys(PINS).length, 2);
});
test('pins: a one-byte change is caught', () => {
    const real = PINS['vendor/original/extension.css'];
    PINS['vendor/original/extension.css'] = '0'.repeat(64);
    try { assert.match(verify(root).join(), /sha256 mismatch/); } finally { PINS['vendor/original/extension.css'] = real; }
});
test('generated original = pinned original + only the text-map phrases', () => {
    if (!existsSync(root + 'src/original.generated.js')) return;   // generated by the build
    const gen = read('src/original.generated.js'), orig = read('vendor/original/extension.js');
    let expect = orig; for (const { from, to } of JSON.parse(read('src/text-map.json'))) expect = expect.split(from).join(to);
    assert.ok(gen.includes(expect), 'the embedded script differs from the pinned file beyond text-map.json');
    assert.ok(gen.includes(JSON.stringify(read('vendor/original/extension.css')).slice(0, -1)), 'the original css is embedded unchanged (overrides are appended after it)');
});
test('manifest: same identifier as the installed 0.4.x, permissions known to older hosts, no embeddings', () => {
    const m = JSON.parse(read('spindle.json'));
    assert.equal(m.identifier, 'memory_cabinet'); assert.equal(m.version, '1.0.0-rc.1');
    assert.deepEqual(m.permissions.slice().sort(), ['chat_mutation', 'characters', 'chats', 'generation', 'world_books'].sort());
    for (const p of m.permissions) assert.ok(MAIN_PERMISSIONS.includes(p), `${p} is not in main's ALL_PERMISSIONS`);
    assert.ok(!m.permissions.includes('embeddings') && !m.permissions.includes('interceptor'));
    assert.equal(m.entry_backend, 'dist/backend.js'); assert.equal(m.entry_frontend, 'dist/frontend.js');
    assert.equal(JSON.parse(read('package.json')).version, m.version);
    // main's spindle.json at the time of the rebuild had this identifier (git show main:spindle.json)
    assert.equal(JSON.parse(readFileSync(root + 'test/fixtures/main-spindle.json', 'utf8')).identifier, m.identifier);
});
test('dist/frontend.js: no unguarded secure-context APIs', () => {
    const js = read('dist/frontend.js');
    for (const bad of ['crypto.subtle', 'navigator.clipboard', 'navigator.share', 'navigator.storage', 'navigator.serviceWorker']) assert.ok(!js.includes(bad), `${bad} found`);
    for (const m of js.matchAll(/crypto\.randomUUID\(\)/g)) assert.match(js.slice(Math.max(0, m.index - 160), m.index), /randomUUID\)\s*(\{|\n)?|\?\.randomUUID/, 'randomUUID call without a feature check');
});
test('dist/backend.js: nothing the Lumiverse scanner rejects (static rules; the real scanner runs in qa/scan-backend.ts)', () => {
    const js = read('dist/backend.js');
    assert.doesNotMatch(js, /\beval\s*\(/); assert.doesNotMatch(js, /\bFunction\s*\(/); assert.doesNotMatch(js, /Buffer\.from\s*\([^)]*['"`]base64['"`]/);
    assert.doesNotMatch(js, /child_process|process\.env|Bun\.spawn|Bun\.file|require\(/);
    assert.doesNotMatch(js, /\bfetch\s*\(/);
});

async function boot(host, { withOld = true } = {}) {
    const { document } = parseHTML('<!doctype html><html><head></head><body></body></html>');
    if (withOld) host.store.set('chats/chat1/data.json', { version: 1, items: [{ id: 'a', layer: 'promises', text: '약속', scope: 'public', status: 'active' }, { id: 'b', layer: 'anchors', text: '앵커', scope: 'public', status: 'active' }, { id: 'c', layer: 'scenes', text: '장면', scope: 'public', status: 'active' }] });
    const stop = start(host.api, { afterMs: 0 });
    const ctx = { ...host.ctx, ui: { registerInputBarAction: () => { const hs = []; return { onClick: f => hs.push(f), destroy() {}, fire: () => hs.forEach(f => f()) }; } } };
    const win = { document, setTimeout, clearTimeout, getComputedStyle: undefined, matchMedia: () => ({ matches: false }), fetch: async () => { throw new Error('net'); } };
    const shim = installShim(ctx, { win, activeChatId: () => 'chat1' });
    return { document, ctx, win, shim, stop };
}
const until = async (fn, ms = 3000) => { const t = Date.now(); while (Date.now() - t < ms) { const v = fn(); if (v) return v; await new Promise(r => setTimeout(r, 10)); } throw new Error('timeout ' + fn); };

test('panel: 0.4.x data -> prompt opens; import stays locked until backup + "I saved it"; then one click imports promises/anchors only', async () => {
    const host = createFakeHost(); const env = await boot(host);
    const panel = createPanel(env.ctx, env.shim, { win: env.win, doc: env.document });
    const realCreate = URL.createObjectURL; URL.createObjectURL = () => { throw new Error('no blob urls here'); };   // force the text-box fallback
    try {
        await panel.promptIfMigrationPending();
        const $ = s => env.document.querySelector(s);
        await until(() => $('#mvx-migrate'));
        assert.match($('#mvx-migrate').textContent, /채팅 1개, 항목 3개/); assert.match($('#mvx-migrate').textContent, /약속·앵커 2개/);
        assert.equal($('#mvx-import').disabled, true); assert.equal($('#mvx-saved').disabled, true);
        $('#mvx-backup').click();
        await until(() => !$('#mvx-saved').disabled || $('textarea.mvx-text'));   // linkedom has no Blob/URL: the text-box fallback shows
        assert.ok($('textarea.mvx-text'), 'fallback text box when the file cannot be created'); assert.match($('textarea.mvx-text').value, /memory-cabinet-lv-backup/);
        assert.equal($('#mvx-import').disabled, true, 'a backup alone is not enough');
        $('#mvx-saved').checked = true; $('#mvx-saved').dispatchEvent(new env.document.defaultView.Event('change', { bubbles: true }));
        await until(() => !$('#mvx-import').disabled);
        $('#mvx-import').click();
        await until(() => host.chat.metadata.memoryCabinetV1?.items?.length === 2);
        assert.deepEqual(host.chat.metadata.memoryCabinetV1.items.map(i => i.type).sort(), ['anchor', 'promise']);
        await until(() => /가져왔어요/.test($('#mvx-migrate')?.textContent || ''));
        assert.match($('#mvx-migrate').textContent, /채팅 1개\(항목 2개\)/); assert.doesNotMatch($('#mvx-migrate').textContent, /건너뜀|실패/);
    } finally { URL.createObjectURL = realCreate; panel.dispose(); env.shim.dispose(); env.stop(); }
});
